H1x = (a2*(b3*N1+N3*b1)-a3*(b1*N2+N1*b2))/(2*detJ);
H2x = (a3*(b1*N2+N1*b2)-a1*(b2*N3+N2*b3))/(2*detJ);
H3x = (a1*(b2*N3+N2*b3)-a2*(b3*N1+N3*b1))/(2*detJ);
H1y = (a2*a1*N3-a3*a1*N2)/(2*detJ);
H2y = (a3*a2*N1-a1*a2*N3)/(2*detJ);
H3y = (a1*a3*N2-a2*a3*N1)/(2*detJ);
Bs = [0 0 N1x  H1x+N1  L1x  0    0 0 N2x  H2x+N2  L2x  0    0 0 N3x  H3x+N3  L3x 0  
      0 0 N1y  H1y  L1y+N1  0    0 0 N2y  H2y   L2y+N2 0    0 0 N3y  H3y  L3y+N3 0];
